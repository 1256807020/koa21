// 业务错误码集中表
// 教学点：用"具名常量 + 注释"替代散落在代码里的魔法数字，
//        前端/后端共享同一份语义，方便国际化与排错。
// 分段约定：
//   0        成功
//   1001-1999 客户端/参数/鉴权类
//   5001-5999 服务端/数据库类
//   9999     未知错误
// ============================================================
module.exports = {
  SUCCESS: 0,

  // —— 客户端 ——
  PARAM_ERROR: 1001, // 参数校验失败
  UNAUTHENTICATED: 1002, // 未登录 / 登录态失效
  FORBIDDEN: 1003, // 已登录但无权限（RBAC 阶段启用）
  NOT_FOUND: 1004, // 资源不存在
  LOGIN_FAIL: 1005, // 账号或密码错误
  CAPTCHA_FAIL: 1006, // 验证码错误
  CSRF_FAIL: 1007, // CSRF token 校验失败
  RATE_LIMIT: 1008, // 登录频率受限 / 被锁定

  // —— 服务端 ——
  DB_ERROR: 5001, // 数据库操作异常
  UNKNOWN: 9999, // 未知错误（兜底层）
};
